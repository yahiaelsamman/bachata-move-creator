// Validate data/*.yaml and write web/data.js for the browser.
//   node scripts/build.mjs           validate + build
//   node scripts/build.mjs --check   validate only
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import yaml from 'js-yaml';

const require = createRequire(import.meta.url);
const MoveGraph = require('../src/graph.js');
const Motion = require('../src/motion.js');
const Limits = require('../src/reach.js');
const root = join(dirname(fileURLToPath(import.meta.url)), '..');

export function loadData() {
  const read = (f) => yaml.load(readFileSync(join(root, 'data', f), 'utf8')) || [];
  return { positions: read('positions.yaml'), moves: read('moves.yaml') };
}

/** Moves whose animation breaks a body limit somewhere (overlap, reach, a hand behind its back, an arm through a body or arm), or that fold an arm with the wrong turn. */
export function realismReport(g) {
  const out = [];
  for (const e of g.edges) {
    const m = g.moveById[e.move];
    if (m.kind === 'compound') continue;
    const A = g.posById[e.from], B = g.posById[e.to];
    const fold = Motion.foldProblem(m, A, B);
    if (fold) { out.push(`${m.id} (${e.from} -> ${e.to}): ${fold}`); continue; }
    const allowed = new Set([...Limits.allowedBehind(A), ...Limits.allowedBehind(B)]);
    for (let k = 0; k <= 20; k++) {
      const found = Limits.problems(Motion.frameAt(m, A, B, k / 20), allowed);
      if (found.length) {
        out.push(`${m.id} (${e.from} -> ${e.to}) at ${Math.round((k / 20) * 100)}%: ${found.map((p) => p.kind + (p.who ? ` ${p.who} ${p.hand}` : '')).join(', ')}`);
        break;
      }
    }
  }
  return out;
}

/** The GitHub "Suggest a move" form, with the current positions as dropdown options. */
export function issueForm(positions) {
  const opts = positions.map((p) => `        - "${p.name.replace(/"/g, '')} (${p.id})"`).join('\n');
  return `# Generated by scripts/build.mjs from data/positions.yaml. Do not edit by hand.
name: Suggest a move
description: Propose a bachata move for the map. No coding needed.
title: "Move: "
labels: ["new move"]
body:
  - type: markdown
    attributes:
      value: |
        Thanks for adding to the map. Every move starts in one position and ends in another,
        like a domino. If you're not sure about a field, leave a note at the bottom.
  - type: input
    id: name
    attributes:
      label: Move name
      description: "Family first, then the variant in brackets, e.g. Hammerlock entry (left arm)"
    validations:
      required: true
  - type: dropdown
    id: from
    attributes:
      label: Starts in
      description: Pick every position the move can start from.
      multiple: true
      options:
${opts}
        - "Another position (describe below)"
    validations:
      required: true
  - type: dropdown
    id: to
    attributes:
      label: Ends in
      options:
        - "Same position it started in (styling)"
${opts}
        - "Another position (describe below)"
    validations:
      required: true
  - type: input
    id: counts
    attributes:
      label: Counts
      description: "How many counts it takes (4, 8, ... or 0 if it happens on the fly)"
  - type: dropdown
    id: level
    attributes:
      label: Level
      options:
        - beginner
        - intermediate
        - advanced
  - type: textarea
    id: lead
    attributes:
      label: How to lead it
      description: Hands, turn direction, timing, anything that makes it work.
  - type: input
    id: video
    attributes:
      label: Video or source (optional)
  - type: textarea
    id: notes
    attributes:
      label: Anything else
`;
}

const isMain = process.argv[1] === fileURLToPath(import.meta.url);
if (isMain) {
  const data = loadData();
  const g = MoveGraph.compile(data);
  const kinds = {};
  for (const m of g.moves) kinds[m.kind] = (kinds[m.kind] || 0) + 1;

  console.log(`${g.positions.length} positions, ${g.moves.length} moves ` +
    `(${Object.entries(kinds).map(([k, n]) => `${n} ${k}`).join(', ')}), ${g.edges.length} edges`);
  for (const w of g.warnings) console.log(`  warning: ${w}`);
  const thin = g.health.filter((h) => h.thin);
  if (thin.length) {
    console.log('  thin positions (aim for 3 ways in and 3 ways out):');
    for (const h of thin) console.log(`    ${h.id.padEnd(14)} in ${h.in}  out ${h.out}`);
  }
  // Realism: animate every move and check bodies, reach and shoulder ranges along the way.
  const unrealistic = realismReport(g);
  if (unrealistic.length) {
    console.log(`  realism: ${unrealistic.length} move(s) break body limits in the animation:`);
    for (const r of unrealistic.slice(0, 15)) console.log(`    ${r}`);
  }
  if (g.errors.length) {
    for (const e of g.errors) console.error(`  ERROR: ${e}`);
    process.exit(1);
  }
  if (!process.argv.includes('--check')) {
    writeFileSync(join(root, '.github', 'ISSUE_TEMPLATE', 'new-move.yml'), issueForm(data.positions));
    console.log('wrote .github/ISSUE_TEMPLATE/new-move.yml');
    writeFileSync(join(root, 'web', 'data.js'),
      '// Generated by scripts/build.mjs from data/*.yaml. Do not edit by hand.\n' +
      `window.BACHATA_DATA = ${JSON.stringify(data, null, 1)};\n`);
    console.log('wrote web/data.js');
  }
}
